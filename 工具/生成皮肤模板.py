def main():
    os.makedirs(OUT, exist_ok=True)

    # 1) 空白皮肤（全透明 64×64）
    blank = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    blank.save(os.path.join(OUT, "空白-皮肤-64.png"))
    print("saved 空白-皮肤-64.png")

    # 2) 10 倍的画布地图
    W = 64 * SCALE
    TOP = 56
    BOT = 46
    H = 64 * SCALE + TOP + BOT
    guide = Image.new("RGBA", (W, H), (250, 250, 252, 255))
    d = ImageDraw.Draw(guide)

    def T(y):
        return y + TOP
    # 网格
    for i in range(0, 65, 4):
        c = (226, 226, 234, 255) if i % 8 else (206, 206, 220, 255)
        d.line([(i * SCALE, TOP), (i * SCALE, H - BOT)], fill=c)
        d.line([(0, i * SCALE + TOP), (W, i * SCALE + TOP)], fill=c)

    for x, y, w, h, color, label, size in BLOCKS:
        box = [x * SCALE, y * SCALE + TOP, (x + w) * SCALE - 1, (y + h) * SCALE + TOP - 1]
        d.rectangle(box, fill=color + (235,), outline=(140, 140, 160, 255))
        font = ImageFont.truetype(r"C:\Windows\Fonts\msyhbd.ttc", size)
        tw = d.textlength(label, font=font)
        if tw <= (w * SCALE - 4):
            d.text(((box[0] + box[2] - tw) / 2, (box[1] + box[3]) / 2 - size / 2), label,
                   font=font, fill=(70, 60, 90, 255))
        else:
            # 竖着写
            ty = box[1] + 2
            for ch in label:
                cw = d.textlength(ch, font=font)
                d.text(((box[0] + box[2] - cw) / 2, ty), ch, font=font, fill=(70, 60, 90, 255))
                ty += size + 1

    d.text((10, 12), "MC 皮肤画布地图（每格 = 1 像素皮肤，放大 10 倍）", font=F_TITLE, fill=(80, 66, 100, 255))
    d.text((10, H - 36), "粉色=头  紫色=第二层(猫耳/头发)  蓝色=身体  黄色=手臂  绿色=腿", font=F_SM, fill=(110, 96, 130, 255))
    guide.save(os.path.join(OUT, "皮肤地图-10倍.png"))
    print("saved 皮肤地图-10倍.png", guide.size)

    # 3) 给妈妈看的「大画布」：512×512 透明，方便直接画（我会缩回 64）
    big = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
    big.save(os.path.join(OUT, "空白-皮肤-512-大画布.png"))
    print("saved 空白-皮肤-512-大画布.png")


if __name__ == "__main__":
    main()
