def rr(x0, y0, x1, y1, r, fill, outline=None, width=1):
    d.rounded_rectangle([x0 * S, y0 * S, x1 * S, y1 * S], radius=r * S,
                        fill=fill, outline=outline, width=width * S)


def el(x0, y0, x1, y1, fill):
    d.ellipse([x0 * S, y0 * S, x1 * S, y1 * S], fill=fill)


def pie(x0, y0, x1, y1, a0, a1, fill):
    d.pieslice([x0 * S, y0 * S, x1 * S, y1 * S], start=a0, end=a1, fill=fill)


def poly(pts, fill):
    d.polygon([(x * S, y * S) for x, y in pts], fill=fill)


def line(pts, fill, width=1):
    d.line([(x * S, y * S) for x, y in pts], fill=fill, width=width * S, joint="curve")


def arc(x0, y0, x1, y1, a0, a1, fill, width=4):
    d.arc([x0 * S, y0 * S, x1 * S, y1 * S], start=a0, end=a1, fill=fill, width=width * S)


def capsule(x0, y0, x1, y1, w, col):
    """带圆头的粗线（画手臂、腿这种）。"""
